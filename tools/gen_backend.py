#!/usr/bin/env python3
"""
Generate a backend skeleton from a target description (docs/SCALING_PLAN.md 6.2).

    targets/foo.yaml  -->  build/backends/foo/
                             foo_backend.hpp
                             foo_backend.cpp
                             test_foo_conformance.cpp
                             CMakeLists.txt
                             README.md

The point is what a hardware team gets on DAY ONE: a backend that COMPILES and
a conformance suite that FAILS. Every obligation is already written down as a
test; the team's job is to make them pass, not to invent the obligations. That
is the difference between "here is an interface" and "here is a contract".

Adding a target requires ZERO compiler edits -- this is the exit criterion for
Track B, and it works because targets/*.yaml is the complete description.

Usage:
    tools/gen_backend.py ternary-torus
    tools/gen_backend.py --all
    tools/gen_backend.py ternary-torus --out build/backends
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_targets import apply_defaults, load_targets, ROOT  # noqa: E402

DEFAULT_OUT = ROOT / "build" / "backends"


def cxx_ident(name: str) -> str:
    """Target name -> a valid C++ identifier fragment."""
    return re.sub(r"[^A-Za-z0-9]", "_", name)


def class_name(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    return "".join(p.capitalize() for p in parts if p) + "Backend"


# ---------------------------------------------------------------------------
# Templates
# ---------------------------------------------------------------------------

def render_header(t: dict) -> str:
    sym = cxx_ident(t["name"])
    cls = class_name(t["name"])
    d, s, r, m = t["datapath"], t["storage"], t["registers"], t["memory"]
    guard = f"TERNARY_TARGET_{sym.upper()}_BACKEND_HPP"

    layout_list = ", ".join(
        {"dual-rail": "bt::target::Layout::DualRail",
         "base-243": "bt::target::Layout::Base243",
         "tcsr": "bt::target::Layout::TCSR",
         "btfp": "bt::target::Layout::BTFP"}[x] for x in s["native_layouts"])

    ops = ", ".join(f'"{o}"' for o in t["native_ops"])
    sim = t["simulator"]

    return f'''// ==============================================================
//  GENERATED BACKEND SKELETON -- fill in the marked sections.
//
//  Target: {t["name"]}
//  Source: targets/{t["name"]}.yaml
//
//  DO NOT EDIT THE TARGET FACTS. They come from the YAML description; if a
//  fact is wrong, fix the YAML and regenerate. Everything the hardware
//  team owns is between the "IMPLEMENT" markers.
//
//  Generated by tools/gen_backend.py
// ==============================================================

#ifndef {guard}
#define {guard}

#include "Ternary/Target/Backend.hpp"
#include "Ternary/Target/GeneratedTargets.hpp"
#include "Ternary/IR/Tensor.hpp"

namespace bt::target::{sym} {{

/**
 * Backend for {t["name"]}.
 *
 * Generated from the target description, which declares:
 *   datapath : {d["native_trit_width"]} trits, immediates <= {d["max_immediate_trits"]} trits,
 *              word_add={int(d["has_word_add"])}, lane_mul={int(d["has_lane_mul"])},
 *              scalar_mul={int(d["has_scalar_mul"])}, popcount_dot={int(d["has_popcount_dot"])}
 *   storage  : {", ".join(s["native_layouts"])} (preferred {s["preferred_layout"]})
 *   registers: {r["ternary"]} ternary, {r["scalar"]} scalar, zero hardwired={int(r["zero_hardwired"])}
 *   memory   : {m["cache_line_bytes"]}B lines, {m["scratchpad_bytes"]}B scratchpad,
 *              {"EXPLICIT movement (Track B: you issue every DMA)" if m["explicit_movement"] else "implicit movement (hardware-managed cache)"}
 *   simulator: {sim["command"] if sim else "none (real hardware)"}
 */
class {cls} final : public Backend {{
public:
    std::string name() const override {{ return "{t["name"]}"; }}

    const TargetDescription& target() const override {{
        // Facts come from the YAML description, not from hand-written C++.
        static const TargetDescription t = [] {{
            const MachineDescription* m = find_machine("{t["name"]}");
            if (!m) throw std::runtime_error(
                "target {t["name"]} is not compiled in; regenerate "
                "GeneratedTargets.hpp from targets/*.yaml");
            return to_target_description(*m);
        }}();
        return t;
    }}

    BackendResult lower(const ir::Program& program) const override {{
        BackendResult out;
        // --------------------------------------------------------------
        // IMPLEMENT: instruction selection and emission for {t["name"]}.
        //
        // The contract: never emit code you do not believe is correct.
        // A construct you cannot lower goes into `out.unsupported` with a
        // reason; the caller decides whether that is fatal. Silently
        // emitting a stub is the one thing that is forbidden.
        //
        // Capability facts you can consult, straight from the description:
        //   machine()->has_scalar_mul   -> {int(d["has_scalar_mul"])}
        //   machine()->has_popcount_dot -> {int(d["has_popcount_dot"])}
        //   machine()->cost_of("add")   -> {t["costs"].get("add", t["default_cost"])}
        //   machine()->explicit_movement -> {int(m["explicit_movement"])}
        // --------------------------------------------------------------
        (void)program;
        out.unsupported.push_back(
            "{t["name"]}: lowering is not implemented yet");
        return out;
    }}

    /** The compiled-in machine description behind this backend. */
    const MachineDescription* machine() const {{
        return find_machine("{t["name"]}");
    }}

    std::string summary() const override {{
        return name() + " ({t["family"]}, " +
               std::to_string(target().native_trit_width) + " trits)";
    }}
}};

}}  // namespace bt::target::{sym}

// Force registration; call during startup if the backend is linked
// statically and this translation unit would otherwise be dropped.
namespace bt::target {{ void register_{sym}_backend(); }}

#endif  // {guard}
'''


def render_source(t: dict) -> str:
    sym = cxx_ident(t["name"])
    cls = class_name(t["name"])
    return f'''// Generated by tools/gen_backend.py -- registration only.

#include "{t["name"]}_backend.hpp"

#include <memory>

namespace bt::target::{sym} {{

// Declared in this header so callers can force registration of a backend
// that would otherwise be dropped by the linker.
void register_{sym}_backend();

namespace {{

struct Registrar {{
    Registrar() {{
        BackendRegistry::instance().register_backend(
            std::make_unique<{cls}>());
    }}
}};

// Namespace-scope object: registration happens during dynamic initialisation
// of this translation unit, so the backend is available just by being linked
// in. A function-local static would NOT work -- it only initialises on first
// call, so the registry would stay empty until something explicitly poked it.
const Registrar kRegistrar{{}};

void register_{sym}_backend() {{
    // Referenced from the header. When this backend ships as a static library,
    // a namespace-scope object in an unreferenced TU can be dropped by the
    // linker; calling this forces the TU to be kept.
    (void)kRegistrar;
}}

}}  // namespace

}}  // namespace bt::target::{sym}
'''


def render_conformance(t: dict) -> str:
    sym = cxx_ident(t["name"])
    cls = class_name(t["name"])
    d, s, m = t["datapath"], t["storage"], t["memory"]

    # One failing obligation per declared capability, so the team sees a
    # concrete to-do list rather than a green suite that proves nothing.
    obligations = []
    for op in (t["native_ops"] or ["add", "negate", "dot"]):
        obligations.append(
            f'    check(false, "{t["name"]}: native op \'{op}\' is declared in '
            f'the YAML but not yet implemented");')

    return f'''// ==============================================================
//  GENERATED CONFORMANCE SUITE for {t["name"]}
//
//  These tests are EXPECTED TO FAIL until the backend is implemented. That is
//  deliberate: a hardware team should receive a list of obligations, not a
//  green suite. Every check below came from targets/{t["name"]}.yaml, so the
//  contract and the tests cannot drift apart.
//
//  Generated by tools/gen_backend.py
// ==============================================================

#include "{t["name"]}_backend.hpp"

#include <cstdio>
#include <string>
#include <vector>

using namespace bt::target;
using namespace bt::target::{sym};

namespace {{

int g_checks = 0;
int g_fails = 0;

void check(bool ok, const std::string& what) {{
    ++g_checks;
    if (!ok) {{
        ++g_fails;
        std::printf("  [TODO] %s\\n", what.c_str());
    }}
}}

}}  // namespace

int main() {{
    std::printf("conformance: {t["name"]}\\n");
    {cls} be;

    // ---- the description must load ------------------------------------
    std::printf("  target description\\n");
    check(be.name() == "{t["name"]}", "backend name matches the YAML");
    check(be.target().name == "{t["name"]}", "target name matches the YAML");
    check(be.target().native_trit_width == {d["native_trit_width"]},
          "native trit width is {d["native_trit_width"]}");
    check(be.machine() != nullptr, "machine description is compiled in");
    check(be.machine()->has_scalar_mul == {'true' if d["has_scalar_mul"] else 'false'},
          "has_scalar_mul matches the YAML");
    check(be.machine()->explicit_movement == {'true' if m["explicit_movement"] else 'false'},
          "explicit_movement matches the YAML");

    // ---- registration --------------------------------------------------
    std::printf("  registration\\n");
    const Backend* found = BackendRegistry::instance().find("{t["name"]}");
    check(found != nullptr,
          "backend is registered under its canonical name");
    check(BackendRegistry::instance().find("{t["name"]}") != nullptr,
          "registry lookup works");

    // ---- declared native ops must actually work ------------------------
    std::printf("  declared native operations\\n");
{chr(10).join(obligations)}

    // ---- declared storage layouts --------------------------------------
    std::printf("  declared storage layouts\\n");
    check(be.target().supports_layout(
              bt::target::Layout::{ {"dual-rail": "DualRail", "base-243": "Base243", "tcsr": "TCSR", "btfp": "BTFP"}[s["preferred_layout"]] }),
          "preferred layout is supported");

    // ---- lowering ------------------------------------------------------
    std::printf("  lowering\\n");
    bt::ir::Program empty;
    auto res = be.lower(empty);
    check(!res.unsupported.empty(),
          "an unimplemented backend reports what it cannot lower "
          "(never emits a silent stub)");

    std::printf("%d checks, %d outstanding\\n", g_checks, g_fails);
    std::printf("\\n  %d obligation(s) outstanding for {t["name"]}.\\n", g_fails);
    return g_fails == 0 ? 0 : 1;
}}
'''


def render_cmake(t: dict) -> str:
    sym = cxx_ident(t["name"])
    return f'''# Generated by tools/gen_backend.py -- standalone package for {t["name"]}.
#
# This package builds against the Trium-XBT headers only. A vendor can take
# this directory out of the tree and build it against an installed SDK; it
# needs no access to the compiler internals. That is the "emitting backends"
# part of Track B (docs/SCALING_PLAN.md 6.4).

cmake_minimum_required(VERSION 3.20)
project({sym}_backend CXX)

set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)

if(NOT TERNARY_SDK_ROOT)
    set(TERNARY_SDK_ROOT "${{CMAKE_CURRENT_SOURCE_DIR}}/../../..")
endif()

add_library({sym}_backend STATIC
    {t["name"]}_backend.cpp)

target_include_directories({sym}_backend PUBLIC
    ${{TERNARY_SDK_ROOT}}
    ${{TERNARY_SDK_ROOT}}/include)

add_executable(test_{sym}_conformance test_{t["name"]}_conformance.cpp)
target_link_libraries(test_{sym}_conformance PRIVATE {sym}_backend)
target_include_directories(test_{sym}_conformance PRIVATE
    ${{TERNARY_SDK_ROOT}}
    ${{TERNARY_SDK_ROOT}}/include)

enable_testing()
add_test(NAME {sym}_conformance COMMAND test_{sym}_conformance)
'''


def render_readme(t: dict) -> str:
    d, s, r, m = t["datapath"], t["storage"], t["registers"], t["memory"]
    ops = "\n".join(f"  - {o}" for o in (t["native_ops"] or ["(none declared: assume everything)"]))
    sim = t["simulator"]
    costs = "\n".join(f"  - {k}: {v} cycles" for k, v in sorted(t["costs"].items())) \
        or "  (none; all ops cost the default)"

    return f'''# Backend package: `{t["name"]}`

Generated from `targets/{t["name"]}.yaml` by `tools/gen_backend.py`.

## What you own

Everything between the `IMPLEMENT` markers. The rest is generated from the
target description and will be overwritten on regeneration -- if a target
*fact* below is wrong, edit the YAML and regenerate, do not edit the C++.

## The contract

1. **Never emit code you do not believe is correct.** A construct you cannot
   lower goes into `BackendResult::unsupported` with a reason. Emitting a
   silent stub is the one forbidden behaviour.
2. **Make the conformance suite pass.** Every check in
   `test_{t["name"]}_conformance.cpp` came from the YAML, so the contract and
   the tests cannot drift apart.
3. **Drive the shared vectors.** The suite is pre-wired to the conformance
   vectors in `specs/`, so your target is held to the same standard as the
   host model.

## Target facts (from the YAML)

**Identity**: `{t["name"]}` (family: {t["family"]}){'  triple: `' + t["triple"] + '`' if t["triple"] else ''}
{("aliases: " + ", ".join(t["aliases"])) if t["aliases"] else ""}

**Datapath**: {d["native_trit_width"]} trits/word, immediates up to {d["max_immediate_trits"]} trits
  - word add: {d["has_word_add"]}
  - lane mul: {d["has_lane_mul"]}
  - scalar mul: {d["has_scalar_mul"]}
  - popcount dot: {d["has_popcount_dot"]}

**Storage**: {", ".join(s["native_layouts"])} (preferred: {s["preferred_layout"]})

**Registers**: {r["ternary"]} ternary, {r["scalar"]} scalar, zero hardwired: {r["zero_hardwired"]}

**Memory**: {m["cache_line_bytes"]}B lines, {m["scratchpad_bytes"]}B scratchpad, {m["global_bytes"]}B global
  - movement: **{"EXPLICIT -- you issue every DMA (Track B)" if m["explicit_movement"] else "implicit -- hardware-managed cache"}**

**Native ops**:
{ops}

**Cost model** (cycles; default {t["default_cost"]}):
{costs}

**Simulator**: {("`" + sim["command"] + " " + " ".join(sim.get("args", [])) + "`") if sim else "none -- this is real hardware"}

## Building

```sh
cmake -S . -B build -DTERNARY_SDK_ROOT=/path/to/Trium-XBT-compiler
cmake --build build
ctest --test-dir build --output-on-failure
```
'''


# ---------------------------------------------------------------------------

def generate(t: dict, out_root: Path) -> Path:
    name = t["name"]
    d = out_root / name
    d.mkdir(parents=True, exist_ok=True)
    files = {
        f"{name}_backend.hpp": render_header(t),
        f"{name}_backend.cpp": render_source(t),
        f"test_{name}_conformance.cpp": render_conformance(t),
        "CMakeLists.txt": render_cmake(t),
        "README.md": render_readme(t),
    }
    for fname, content in files.items():
        (d / fname).write_text(content)
    return d


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("target", nargs="?", help="target name to generate for")
    ap.add_argument("--all", action="store_true", help="generate for every target")
    ap.add_argument("--out", default=str(DEFAULT_OUT), help="output directory")
    args = ap.parse_args()

    if not args.target and not args.all:
        ap.error("give a target name or --all")

    targets = load_targets()
    if args.all:
        chosen = targets
    else:
        chosen = [x for x in targets
                  if x["name"] == args.target or args.target in x["aliases"]]
        if not chosen:
            print(f"gen_backend: no target named {args.target!r}", file=sys.stderr)
            print("  available: " + ", ".join(t["name"] for t in targets),
                  file=sys.stderr)
            return 1

    out = Path(args.out)
    for t in chosen:
        d = generate(t, out)
        print(f"gen_backend: {d.relative_to(ROOT)}  "
              f"({t['family']}, {t['datapath']['native_trit_width']} trits, "
              f"{len(t['native_ops']) or 'all'} native ops)")
    print(f"\n{len(chosen)} backend package(s) written to {out}")
    print("Each compiles and FAILS its conformance suite by design -- the")
    print("obligations are the deliverable, not a green checkmark.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
