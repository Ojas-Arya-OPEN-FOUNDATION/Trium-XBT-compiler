#ifndef TERNARY_TARGET_XBT_BACKEND_HPP
#define TERNARY_TARGET_XBT_BACKEND_HPP

/**
 * @file include/Ternary/Target/XbtBackend.hpp
 * @brief The RISC-V Xbt backend, expressed through the Backend interface.
 *
 * This is the reference example of what a backend is: a target description
 * plus a lowering that consumes the backend-neutral core IR. Nothing else in
 * the compiler needs to know it exists -- it registers itself.
 */

#include "Backend.hpp"
#include "TargetDescription.hpp"
#include "XbtInstructionSelector.hpp"

namespace bt::target {

class XbtBackend final : public Backend {
public:
    std::string name() const override { return "xbt"; }

    const TargetDescription& target() const override {
        static const TargetDescription t = xbt_target_v2();
        return t;
    }

    BackendResult lower(const ir::Program& program) const override {
        xbt::InstructionSelector sel(
            static_cast<int>(target().ternary_registers) / 2);
        BackendResult out;

        out.output += "// Generated by Trium-XBT -- target " + target().name + "\n";
        out.output += "// RISC-V \"Xbt\" custom-0 (opcode 0x0B), balanced ternary\n";
        out.output += "// Every instruction emitted here is Z3-verified against\n";
        out.output += "// balanced-ternary arithmetic: see verification/verify_isa.py\n";
        out.output += "//\n";
        out.output += "// " + target().describe();
        out.output += "\n";

        for (const auto& f : program.functions) {
            try {
                auto lowered = sel.lower_function(f);
                out.output += xbt::emit_assembly(lowered);
            } catch (const std::exception& e) {
                // Report, do not guess. A partially-lowered function would be
                // silently wrong code, which is worse than no code.
                out.unsupported.push_back(f.name + ": " + e.what());
            }
        }

        out.ok = true;
        return out;
    }

    std::string summary() const override {
        return "xbt  -- RISC-V custom-0 balanced ternary (Z3-verified ISA, "
               "64-trit dual-rail registers)";
    }
};

} // namespace bt::target

#endif // TERNARY_TARGET_XBT_BACKEND_HPP
