/**
 * @file GLSL.hpp
 * @brief Real GLSL 450 compute-kernel backend for the verified core IR.
 *
 * This is the second backend over ir::Program, alongside ir::LLVMEmitter.
 * Same frontend, same lowering, same verification - only the emission
 * differs. It compiles a .bt FUNCTION into an actual GLSL compute kernel that
 * maps that function over a device buffer. It does not emit a canned template:
 * the emitted arithmetic comes from the user's source.
 *
 * Deliberately narrow and honest about it. Supported:
 *   Integer, Floating, Parameter, Add, Sub, Mul, Negate, IntCast, IntToFloat,
 *   Equal, NotEqual, Less, Greater, LessEqual, GreaterEqual, Spaceship,
 *   SignSelect (expr and statement), Sqrt, Abs, Fma, Call.
 *
 * Rejected with a precise message naming the construct and its source line:
 *   Print      - host I/O has no meaning in a compute kernel
 *   Intrinsic  - host runtime call
 *   Packed     - packed-word constants have no device representation yet
 *   DigitAnd/Or/Xor - need the ternary logic helper ported (see bt.core.logic
 *                     in LLVM.hpp); not yet emitted
 *
 * Semantics are copied from LLVMEmitter exactly, including the two that are
 * easy to get wrong:
 *   - comparisons yield 1 for true and -1 for false, not 0/1
 *   - SignSelect branches on the SIGN of the value: >0, <0, else 0
 */
#ifndef TERNARY_IR_GLSL_HPP
#define TERNARY_IR_GLSL_HPP

#include "Program.hpp"

#include <set>
#include <sstream>
#include <stdexcept>
#include <string>
#include <vector>

namespace bt {
namespace ir {

class GLSLEmitter {
public:
    // Explicit constructor rather than default member initialisers: a
    // default argument of Config{} in generate() below is parsed before the
    // enclosing class is complete, which GCC rejects.
    struct Config {
        unsigned workgroup;
        bool     emit_fp64;         // required only if the program uses Float64
        explicit Config(unsigned wg = 64, bool fp64 = true)
            : workgroup(wg), emit_fp64(fp64) {}
    };

    /**
     * @brief Compile `entry` into a GLSL compute kernel.
     * @throws std::invalid_argument naming the unsupported construct rather
     *         than silently emitting something that is not the user's program.
     */
    std::string generate(const Program& p, const std::string& entry,
                         const Config& cfg = Config{}) {
        entry_ = entry;
        cfg_ = cfg;
        const Function* fn = nullptr;
        for (const auto& f : p.functions)
            if (f.name == entry) { fn = &f; break; }
        if (!fn)
            throw std::invalid_argument(
                "GLSL backend: no function named '" + entry +
                "' in this program. --emit-vulkan compiles a named function; "
                "this program defines " + std::to_string(p.functions.size()) + ".");

        // The mapping kernel is a map over one buffer, so the entry must be a
        // unary scalar function. Anything else is rejected, not adapted.
        if (fn->parameters.size() != 1)
            throw std::invalid_argument(
                "GLSL backend: '" + entry + "' takes " +
                std::to_string(fn->parameters.size()) +
                " parameters; the compute kernel maps a unary function over an "
                "input buffer, so exactly 1 is required.");
        if (!numeric(fn->parameters[0].type))
            throw std::invalid_argument(
                "GLSL backend: '" + entry + "' takes a non-numeric parameter.");
        if (!numeric(fn->result))
            throw std::invalid_argument(
                "GLSL backend: '" + entry +
                "' returns a non-numeric type; a compute kernel that maps to a "
                "buffer must return a value.");

        uses_fp64_ = (fn->parameters[0].type == Type::Float64 ||
                      fn->result == Type::Float64);

        std::ostringstream o;
        o << "#version 450\n";
        o << "#extension GL_ARB_gpu_shader_int64 : require\n";
        if (uses_fp64_ && cfg_.emit_fp64)
            o << "#extension GL_ARB_gpu_shader_fp64 : require\n";
        o << "// Generated by bt-compiler from .bt source. This is a real\n"
          << "// lowering of the user's program, not a canned template.\n"
          << "// Source function: " << entry << "\n\n";
        o << "layout(local_size_x = " << cfg_.workgroup << ") in;\n";
        o << "layout(binding = 0) readonly  buffer BufIn  { "
          << glsl(fn->parameters[0].type) << " in_data[]; };\n";
        o << "layout(binding = 1) writeonly buffer BufOut { "
          << glsl(fn->result) << " out_data[]; };\n";
        o << "layout(push_constant) uniform PC { uint count; } pc;\n\n";

        // Emit the entry function plus anything it calls (transitively).
        std::set<std::string> emitted;
        emit_function_deps(p, entry, emitted, o);

        o << "\nvoid main() {\n";
        o << "    uint i = gl_GlobalInvocationID.x;\n";
        o << "    if (i >= pc.count) return;\n";
        o << "    out_data[i] = bt_" << sanitise(entry) << "(in_data[i]);\n";
        o << "}\n";
        return o.str();
    }

private:
    std::string entry_;
    Config     cfg_;
    bool       uses_fp64_{false};

    static std::string sanitise(const std::string& s) {
        std::string r;
        for (char c : s) r += (isalnum((unsigned char)c) || c == '_') ? c : '_';
        return r;
    }

    static const char* glsl(Type t) {
        switch (t) {
        case Type::Float64: return "double";
        case Type::Void:    return "void";
        default:            return "int64_t";   // Int39 / Trit / Positional39
        }
    }

    void emit_function_deps(const Program& p, const std::string& name,
                            std::set<std::string>& done, std::ostringstream& o) {
        if (done.count(name)) return;
        done.insert(name);
        for (const auto& f : p.functions)
            if (f.name == name) {
                for (const auto& s : f.body) collect_calls(s, p, done, o);
                o << glsl(f.result) << " bt_" << sanitise(name) << "(";
                for (size_t i = 0; i < f.parameters.size(); ++i)
                    o << (i ? ", " : "") << glsl(f.parameters[i].type)
                      << " v" << f.parameters[i].symbol;
                o << ") {\n";
                for (const auto& s : f.body) statement(s, 1, o);
                o << "}\n\n";
                return;
            }
        throw std::invalid_argument("GLSL backend: unresolved call to '" + name + "'");
    }

    void collect_calls(const Statement& s, const Program& p,
                       std::set<std::string>& done, std::ostringstream& o) {
        if (s.value) collect_calls_expr(*s.value, p, done, o);
        for (const auto& b : {&s.body, &s.alternative, &s.negative})
            for (const auto& c : *b) collect_calls(c, p, done, o);
    }

    void collect_calls_expr(const Expr& e, const Program& p,
                            std::set<std::string>& done, std::ostringstream& o) {
        if (e.op == Op::Call && !done.count(e.name))
            emit_function_deps(p, e.name, done, o);
        for (const auto& c : e.operands) collect_calls_expr(*c, p, done, o);
    }

    // ---------------- statements ----------------
    void statement(const Statement& s, int ind, std::ostringstream& o) {
        const std::string pad(ind * 4, ' ');
        switch (s.kind) {
        case StatementKind::Let:
            o << pad << glsl(s.type) << " v" << s.symbol << " = "
              << expression(*s.value) << ";\n";
            break;
        case StatementKind::Assign:
            o << pad << "v" << s.symbol << " = " << expression(*s.value) << ";\n";
            break;
        case StatementKind::Evaluate:
            o << pad << expression(*s.value) << ";\n";
            break;
        case StatementKind::Block:
            o << pad << "{\n";
            for (const auto& b : s.body) statement(b, ind + 1, o);
            o << pad << "}\n";
            break;
        case StatementKind::Return:
            o << pad << "return" << (s.value ? " " + expression(*s.value) : "")
              << ";\n";
            break;
        case StatementKind::If:
            // Condition is the SIGN test, exactly as LLVMEmitter does it:
            // compare(value, positive=true) -> value > 0.
            o << pad << "if (" << expression(*s.value) << " > 0) {\n";
            for (const auto& b : s.body) statement(b, ind + 1, o);
            if (!s.alternative.empty()) {
                o << pad << "} else {\n";
                for (const auto& b : s.alternative) statement(b, ind + 1, o);
            }
            o << pad << "}\n";
            break;
        case StatementKind::While:
            o << pad << "while (" << expression(*s.value) << " > 0) {\n";
            for (const auto& b : s.body) statement(b, ind + 1, o);
            o << pad << "}\n";
            break;
        case StatementKind::SignSelect: {
            // Three-way on the sign: >0 -> body, <0 -> negative, else alternative.
            const std::string v = "bt_sel_" + std::to_string(ind);
            o << pad << "{\n";
            o << pad << "    " << glsl(s.value->type) << " " << v << " = "
              << expression(*s.value) << ";\n";
            o << pad << "    if (" << v << " > 0) {\n";
            for (const auto& b : s.body) statement(b, ind + 2, o);
            o << pad << "    } else if (" << v << " < 0) {\n";
            for (const auto& b : s.negative) statement(b, ind + 2, o);
            o << pad << "    } else {\n";
            for (const auto& b : s.alternative) statement(b, ind + 2, o);
            o << pad << "    }\n";
            o << pad << "}\n";
            break;
        }
        }
    }

    // ---------------- expressions ----------------
    std::string expression(const Expr& e) {
        switch (e.op) {
        case Op::Integer:
            // int64_t literal suffix keeps it from being truncated to int.
            return std::to_string(e.integer) + "L";
        case Op::Floating: {
            std::ostringstream d;
            d.precision(17);
            d << e.floating;
            return d.str();
        }
        case Op::Parameter:
            return "v" + std::to_string(e.symbol);
        case Op::Negate:
            if (e.type == Type::Float64) return "(-" + expression(*e.operands[0]) + ")";
            return "(0L - " + expression(*e.operands[0]) + ")";   // matches LLVM sub i64 0, a
        case Op::Add: case Op::Sub: case Op::Mul: {
            const char* sym = e.op == Op::Add ? "+" : e.op == Op::Sub ? "-" : "*";
            return "(" + expression(*e.operands[0]) + " " + sym + " " +
                   expression(*e.operands[1]) + ")";
        }
        case Op::IntCast:
            return expression(*e.operands[0]);   // identity, as in LLVM
        case Op::IntToFloat:
            return "(double)(" + expression(*e.operands[0]) + ")";
        case Op::Abs:
            return "abs(" + expression(*e.operands[0]) + ")";
        case Op::Sqrt:
            return "sqrt(" + expression(*e.operands[0]) + ")";
        case Op::Fma:
            return "fma(" + expression(*e.operands[0]) + ", " +
                   expression(*e.operands[1]) + ", " +
                   expression(*e.operands[2]) + ")";
        case Op::Spaceship: {
            const std::string a = expression(*e.operands[0]);
            const std::string b = expression(*e.operands[1]);
            return "((" + a + " > " + b + ") ? 1L : ((" + a + " < " + b +
                   ") ? -1L : 0L))";
        }
        case Op::SignSelect: {
            // operands: condition, positive, zero, negative
            const std::string c = expression(*e.operands[0]);
            const std::string p = expression(*e.operands[1]);
            const std::string z = expression(*e.operands[2]);
            const std::string n = expression(*e.operands[3]);
            return "((" + c + " > 0) ? (" + p + ") : ((" + c + " < 0) ? (" +
                   n + ") : (" + z + ")))";
        }
        case Op::Equal: case Op::NotEqual: case Op::Less:
        case Op::Greater: case Op::LessEqual: case Op::GreaterEqual: {
            const char* sym =
                e.op == Op::Equal ? "==" : e.op == Op::NotEqual ? "!=" :
                e.op == Op::Less ? "<" : e.op == Op::Greater ? ">" :
                e.op == Op::LessEqual ? "<=" : ">=";
            const std::string a = expression(*e.operands[0]);
            const std::string b = expression(*e.operands[1]);
            // LLVM returns i64 1 / -1, not 0/1. Match it exactly.
            return "((" + a + " " + sym + " " + b + ") ? 1L : -1L)";
        }
        case Op::Call: {
            std::string s = "bt_" + sanitise(e.name) + "(";
            for (size_t i = 0; i < e.operands.size(); ++i)
                s += (i ? ", " : "") + expression(*e.operands[i]);
            return s + ")";
        }
        case Op::Print:
            throw std::invalid_argument(
                "GLSL backend: 'print' at line " + std::to_string(e.line + 1) +
                " is host I/O and has no meaning inside a compute kernel. "
                "Factor the arithmetic into a function and compile that.");
        case Op::Intrinsic:
            throw std::invalid_argument(
                "GLSL backend: host intrinsic '" + e.name + "' at line " +
                std::to_string(e.line + 1) + " has no device implementation.");
        case Op::Packed:
            throw std::invalid_argument(
                "GLSL backend: packed-word constant at line " +
                std::to_string(e.line + 1) +
                " has no device representation yet.");
        case Op::DigitAnd: case Op::DigitOr: case Op::DigitXor:
            throw std::invalid_argument(
                "GLSL backend: ternary digit-wise " +
                std::string(e.op == Op::DigitAnd ? "AND" :
                            e.op == Op::DigitOr ? "OR" : "XOR") +
                " at line " + std::to_string(e.line + 1) +
                " requires the bt.core.logic helper, which is not yet emitted "
                "for GLSL.");
        default:
            throw std::invalid_argument(
                "GLSL backend: unsupported core IR operation at line " +
                std::to_string(e.line + 1));
        }
    }
};

} // namespace ir
} // namespace bt

#endif
